#!/usr/bin/env bash
# Build local optimized evaluation APKs, upload them to a GitHub prerelease,
# update website/src/release.generated.ts, and trigger the existing Pages workflow.
#
# Default safety: a local release keystore is required. To make a temporary
# debug-signed evaluation build instead, set ALLOW_DEBUG_EVALUATION=true.
# Debug-signed builds cannot reliably update an APK from another signing key.

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

branch="${BRANCH:-dev}"
repository="${GITHUB_REPOSITORY:-$(gh repo view --json nameWithOwner --jq .nameWithOwner)}"

require_command() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "Required command not found: $1" >&2
    exit 1
  }
}

for command in flutter gh git node pnpm; do
  require_command "$command"
done

if [[ "$(git branch --show-current)" != "$branch" ]]; then
  echo "Checkout the $branch branch before publishing." >&2
  exit 1
fi

if ! git diff --quiet || ! git diff --cached --quiet; then
  echo "Commit or stash tracked changes before publishing a local release." >&2
  exit 1
fi

if [[ ! -f android/key.properties && "${ALLOW_DEBUG_EVALUATION:-false}" != "true" ]]; then
  cat >&2 <<'EOF'
No android/key.properties release keystore was found.
Create a stable local signing configuration before publishing so later APKs can
update in place. For a one-off non-upgradeable test artifact only, run:
  ALLOW_DEBUG_EVALUATION=true scripts/publish-local-evaluation.sh
EOF
  exit 1
fi

git pull --ff-only origin "$branch"
flutter pub get

if [[ -f android/key.properties ]]; then
  signing_description="Locally built stable-signed evaluation release"
  flutter build apk --release --split-per-abi --target-platform android-arm,android-arm64
else
  signing_description="Locally built debug-signed evaluation release"
  ORG_GRADLE_PROJECT_allowDebugReleaseSigning=true \
    flutter build apk --release --split-per-abi --target-platform android-arm,android-arm64
fi

version_line="$(awk '/^version:/{print $2; exit}' pubspec.yaml)"
version_name="${version_line%%+*}"
build_number="${version_line#*+}"
[[ "$build_number" == "$version_line" ]] && build_number="0"

release_tag="local-optimized-v${version_name}-b${build_number}-$(date -u +%Y%m%d%H%M%S)"
arm64_asset="app-arm64-v8a-release.apk"
armv7_asset="app-armeabi-v7a-release.apk"
arm64_url="https://github.com/${repository}/releases/download/${release_tag}/${arm64_asset}"
armv7_url="https://github.com/${repository}/releases/download/${release_tag}/${armv7_asset}"

gh release create "$release_tag" \
  "build/app/outputs/flutter-apk/${arm64_asset}" \
  "build/app/outputs/flutter-apk/${armv7_asset}" \
  --repo "$repository" \
  --title "3ialna local optimized evaluation ${version_name} (${build_number})" \
  --notes "${signing_description}. Release-mode optimized APKs for arm64 and armv7. This is not a Play Store release." \
  --prerelease

published_at="$(date -u +%Y-%m-%dT%H:%M:%S.000Z)"
cat > website/src/release.generated.ts <<EOF
// Generated by scripts/publish-local-evaluation.sh. Do not add secrets here.
export const currentRelease = {
  platform: "Android",
  version: "$version_name",
  build: "$build_number",
  distribution: "$signing_description",
  downloadUrl: "$arm64_url",
  downloadUrls: {
    arm64: "$arm64_url",
    armv7: "$armv7_url",
  },
  publishedAt: "$published_at",
} as const;
EOF

pnpm --dir website build
git add website/src/release.generated.ts
git commit -m "chore(website): sync local APK release [skip ci]"
git pull --rebase origin "$branch"
git push origin "$branch"
gh workflow run deploy-website.yml --repo "$repository" --ref "$branch"

echo "Published $release_tag"
echo "arm64: $arm64_url"
echo "GitHub Pages deployment was triggered for $branch."
